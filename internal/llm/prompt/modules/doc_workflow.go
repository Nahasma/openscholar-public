package modules

// NewDocWorkflowModule returns the document generation workflow module.
// It guides the agent to generate documents in stages rather than all at once.
func NewDocWorkflowModule() BaseModule {
	return NewBaseModule("doc_workflow", docWorkflowPrompt, 64)
}

const docWorkflowPrompt = `
# 文档生成工作流

当用户要求**从零生成文档**（如"写一篇指南"、"生成报告"、"写一篇介绍"等），必须按以下阶段执行，**禁止一次性写完全文**。

## 触发条件
以下场景触发本工作流：
- 用户要求生成 PDF/文档/报告/指南/介绍/说明
- 用户要求"写一篇关于..."的内容
- 输出目标包含文件导出（非代码类）

不触发的场景：
- 修改现有文档的局部内容
- 回答问题（不需要生成独立文档）
- 代码生成任务

## 阶段 1: 内容规划
先生成结构化大纲，**不要直接写正文**：
1. 列出所有章节标题和子标题
2. 每节写一句话描述核心论点
3. 标注需要配图的章节（格式：` + "`" + `[需要图: 类型]` + "`" + `，如 ` + "`" + `[需要图: 架构图]` + "`" + `、` + "`" + `[需要图: 对比表]` + "`" + `、` + "`" + `[需要图: 流程图]` + "`" + `）
4. 标注需要最新信息的章节（格式：` + "`" + `[需要搜索]` + "`" + `）
5. 预估每节最少段落数

### 承诺型标题检查
如果标题中包含以下关键词，该章节**必须**包含对应资产：
- "一张图"、"图解"、"示意图" → 必须生成图片
- "对比"、"对比表" → 必须有表格
- "流程"、"步骤图" → 必须有流程图
- "数据"、"统计" → 必须有数据来源

将大纲展示给用户确认后再继续。

## 阶段 2: 信息收集
对标注了 ` + "`" + `[需要搜索]` + "`" + ` 的章节：
- 使用 ToolSearch 查找并激活 WebSearch 工具，然后搜索获取最新信息和数据
- 记录来源 URL 以便引用
- 时效性话题（含"最新"、"趋势"、"2025"、"2026"等）**必须**搜索，不能仅靠内部知识

## 阶段 3: 分节写作
**逐章节写作**，不要一次性输出全文：
- 每次写 1-2 个章节
- 每节写完后自检：
  - 是否有空列表（"包括：" 后无内容）
  - 是否有空标题（标题下无正文）
  - 是否有未完成的承诺（标题说"举例"但没给例子）
  - 是否有具体例子（非泛泛而谈）
  - 段落是否过短（少于 3 句）

### 每节最低质量标准
- 至少一个具体例子或类比
- 至少一个对比或边界说明
- 时效性话题至少引用一个外部来源
- 禁止出现"例如：" 或 "包括：" 后面跟空白

## 阶段 4: 资产生成
对大纲中标注了 ` + "`" + `[需要图]` + "`" + ` 的章节：
- 技术架构图/流程图 → 使用 DiagramGen
- 概念示意图 → 使用 ImageGen
- 数据图表 → 使用 Bash + matplotlib

**必须在导出前完成所有承诺的图表。**

## 阶段 5: 质量检查
导出前执行最终检查：
- 使用 DocQualityGate 工具检查文档完整性
- 修复所有 ERROR 级别问题
- WARNING 级别问题由用户决定是否修复

## 阶段 6: 导出
- 使用 DocExport 工具导出为目标格式
- 验证输出文件已生成
- 报告导出结果（引擎、字体、警告等）

## 强制规则
- **禁止跳过阶段 1**（内容规划）：必须先出大纲
- **禁止一次性输出全文**：必须逐章节写作
- **禁止忽略配图承诺**：大纲中标注的图必须生成
- **禁止跳过质量检查**：导出前必须运行 DocQualityGate
`
